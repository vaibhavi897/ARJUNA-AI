def _role(
    name: str,
    slug: str,
    domain: str,
    short_label: str,
    description: str,
    weights: tuple[float, float, float, float, float, float, float],
    expectations: tuple[float, float, int, int, int],
    keywords: list[str],
    project_categories: list[str],
    required: list[tuple[str, str, str, float]],
    order: int,
) -> dict[str, Any]:
    """``required`` items are (skill_slug, importance, expected_proficiency, weight)."""
    return {
        "name": name,
        "slug": slug,
        "domain_slug": domain,
        "short_label": short_label,
        "description": description,
        "display_order": order,
        "weights": {
            "skills": weights[0],
            "projects": weights[1],
            "academics": weights[2],
            "experience": weights[3],
            "certifications": weights[4],
            "domain_knowledge": weights[5],
            "resume_quality": weights[6],
        },
        "min_cgpa": expectations[0],
        "target_cgpa": expectations[1],
        "expected_projects": expectations[2],
        "expected_internships": expectations[3],
        "expected_certifications": expectations[4],
        "resume_keywords": keywords,
        "relevant_project_categories": project_categories,
        "required_skills": required,
    }


